import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const html = `<!DOCTYPE html>
<html lang="de">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover" />
  <meta name="description" content="FREYRAUM — Immersive Digital Exhibition Platform" />
  <title>freyraum — immersive gallery</title>
  <link rel="stylesheet" href="./style.css" />
</head>
<body>
  <div id="app"></div>
  <script>
    window.__FREYRAUM_PREVIEW_ASSET_FAILURE__ = function (file) {
      const app = document.getElementById('app');
      if (!app) return;
      app.innerHTML = '';
      const section = document.createElement('section');
      section.setAttribute('role', 'alert');
      section.style.cssText = 'max-width:42rem;margin:10vh auto;padding:2rem;font-family:system-ui,sans-serif;color:#12171b;background:#fff;border-radius:1rem';
      const title = document.createElement('h1');
      title.textContent = 'Lokale Vorschau ist unvollständig';
      const body = document.createElement('p');
      body.textContent = 'Die erforderliche Datei ' + file + ' fehlt. Bitte führen Sie den FREYRAUM-Build erneut aus.';
      section.append(title, body);
      app.appendChild(section);
    };
  </script>
  <!-- v0.07: customer-managed artworks. Generated by scripts/import-artworks.mjs.
       Loads as a global window injection so the file:// preview works without a server. -->
  <script src="./customer-artworks.js" onerror="window.__FREYRAUM_PREVIEW_ASSET_FAILURE__('customer-artworks.js')"></script>
  <script src="./customer-audio.js" onerror="window.__FREYRAUM_PREVIEW_ASSET_FAILURE__('customer-audio.js')"></script>
  <script src="./freyraum-gallery.js" onerror="window.__FREYRAUM_PREVIEW_ASSET_FAILURE__('freyraum-gallery.js')"></script>
</body>
</html>
`;

const editorHtml = `<!DOCTYPE html>
<html lang="de">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover" />
  <meta name="description" content="FREYRAUM Artwork Placement Editor" />
  <title>FREYRAUM — Artwork Placement Editor</title>
  <link rel="stylesheet" href="./style.css" />
  <script>
    const editorUrl = new URL(window.location.href);
    editorUrl.searchParams.set('hubCalibrate', '1');
    editorUrl.searchParams.set('placementEditor', '1');
    window.history.replaceState(null, '', editorUrl);
  </script>
</head>
<body class="placement-editor">
  <div id="app"></div>
  <script src="./customer-artworks.js"></script>
  <script src="./customer-audio.js"></script>
  <script src="./freyraum-gallery.js"></script>
</body>
</html>
`;

const bundlePath = 'customer-preview/freyraum-gallery.js';
const secureRandom = `function freyraumPseudoRandom(){const cryptoApi=globalThis.crypto;if(cryptoApi&&cryptoApi.getRandomValues){const values=new Uint32Array(1);cryptoApi.getRandomValues(values);return values[0]/4294967296}const now=Date.now();const perf=globalThis.performance&&globalThis.performance.now?globalThis.performance.now():0;return (Math.sin(now+perf)*10000)%1}\n`;
const bundle = readFileSync(bundlePath, 'utf8')
  .replaceAll('Math.random()', 'freyraumPseudoRandom()');

writeFileSync(bundlePath, secureRandom + bundle);
writeFileSync('customer-preview/app.html', html);
writeFileSync('customer-preview/placement-editor.html', editorHtml);

// v0.07: write a stub customer-artworks.js when none exists yet so the
// `<script src="./customer-artworks.js">` tag does not 404 before the
// customer has run the importer for the first time. A real run of
// `scripts/import-artworks.mjs` overwrites this file with the manifest.
const stubPath = 'customer-preview/customer-artworks.js';
if (!existsSync(stubPath)) {
  writeFileSync(
    stubPath,
    '// Stub generated by scripts/write-local-preview.mjs.\n' +
      '// Replaced by scripts/import-artworks.mjs once the customer adds pictures.\n' +
      '(() => {\n' +
      "  const script = document.currentScript instanceof HTMLScriptElement ? document.currentScript : null;\n" +
      "  const fallbackHref = typeof window !== 'undefined' && window.location ? window.location.href : '';\n" +
      "  let assetBaseUrl = fallbackHref;\n" +
      '  try {\n' +
      "    assetBaseUrl = new URL('./', (script && script.src) || fallbackHref).href;\n" +
      '  } catch {}\n' +
      "  const bundle = { schemaVersion: 1, bundleId: 'stub-empty', generatedAt: null, assetBaseUrl, artworks: [] };\n" +
      '  window.__FREYRAUM_ARTWORK_BUNDLE__ = bundle;\n' +
      '  window.__FREYRAUM_ARTWORKS = bundle.artworks;\n' +
      '})();\n'
  );
}

const audioStubPath = 'customer-preview/customer-audio.js';
if (!existsSync(audioStubPath)) {
  writeFileSync(
    audioStubPath,
    '// Stub generated by scripts/write-local-preview.mjs.\n' +
      '// Replaced by scripts/import-artworks.mjs when customer audio exists.\n' +
      'window.__FREYRAUM_AUDIO = { sources: [] };\n'
  );
}
